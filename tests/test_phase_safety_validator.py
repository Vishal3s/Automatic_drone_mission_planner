# ---------------------------------------------------------------------
# Full chain -- matches the spec's SUCCESS CRITERIA
# ---------------------------------------------------------------------


def test_full_chain_unsafe_revised_mission_is_always_rejected_with_a_fallback():
    manager = _manager_at()
    context = _context(manager, battery_remaining_percent=0.0)  # guarantees battery infeasibility
    unsafe_proposal = RevisedMissionProposal(
        remaining_waypoints=[
            MissionItem(sequence=1, command=MissionCommand.WAYPOINT, latitude=1.018, longitude=2.000, altitude=30),
            MissionItem(sequence=2, command=MissionCommand.RETURN_TO_LAUNCH),
        ],
        recommended_action=RecommendedAction.CONTINUE,
        reason="Proceeding despite critical battery.",
        confidence=0.4,
    )
    result = ReplanningSafetyValidator().validate(
        unsafe_proposal, context, manager.snapshot(), home_latitude_deg=HOME_LAT, home_longitude_deg=HOME_LON
    )

    assert result.status == SafetyValidationStatus.REJECTED
    assert result.approved is False
    assert result.approved_mission is None
    assert result.fallback_action is not None
    assert result.fallback_reason
    try:
        enforce_before_mavsdk(result)
        assert False, "an unsafe mission must never reach the MAVSDK conversion step"
    except UnsafeMissionError:
        pass
