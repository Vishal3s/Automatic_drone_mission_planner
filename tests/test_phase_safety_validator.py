from app.trigger.events import EventSeverity, EventSource, EventType, ReplanningEvent

HOME_LAT, HOME_LON = 1.000, 2.000


def _mission() -> Mission:
    return Mission(
        mission_name="Safety validator test mission",
        mission_items=[
            MissionItem(sequence=1, command=MissionCommand.TAKEOFF, altitude=30),
            MissionItem(sequence=2, command=MissionCommand.WAYPOINT, latitude=1.000, longitude=2.000, altitude=30),
            MissionItem(sequence=3, command=MissionCommand.WAYPOINT, latitude=1.009, longitude=2.000, altitude=30),
            MissionItem(sequence=4, command=MissionCommand.WAYPOINT, latitude=1.018, longitude=2.000, altitude=30),
            MissionItem(sequence=5, command=MissionCommand.RETURN_TO_LAUNCH),
        ],
    )


def _manager_at(current_sequence: int = 3) -> MissionStateManager:
    manager = MissionStateManager()
    manager.start(_mission())
    manager.mark_validated()
    manager.mark_uploaded()
    manager.mark_running()
    manager.record_progress(current=current_sequence, total=5)
    return manager


def _context(manager: MissionStateManager, battery_remaining_percent: float | None = 0.5, **safety_kwargs):
    drone_state = DroneState(
        latitude_deg=1.009, longitude_deg=2.000, relative_altitude_m=30.0,
        battery_remaining_percent=battery_remaining_percent,
    )
    event = ReplanningEvent(
        event_type=EventType.BATTERY_DEVIATION, severity=EventSeverity.HIGH, source=EventSource.TELEMETRY,
        mission_id=manager.snapshot().mission_id, drone_state=drone_state, mission_state=manager.snapshot(),
    )
    constraints = SafetyConstraints.from_settings()
    for k, v in safety_kwargs.items():
        setattr(constraints, k, v)
    return ReplanningContextBuilder().build(event, manager.snapshot(), drone_state, safety_constraints=constraints)


def _safe_continue_proposal() -> RevisedMissionProposal:
    return RevisedMissionProposal(
        remaining_waypoints=[
            MissionItem(sequence=1, command=MissionCommand.WAYPOINT, latitude=1.018, longitude=2.000, altitude=30),
            MissionItem(sequence=2, command=MissionCommand.RETURN_TO_LAUNCH),
        ],
        recommended_action=RecommendedAction.CONTINUE,
        reason="Battery sufficient to reach WP4 then return home.",
        confidence=0.85,
    )


def _rth_only_proposal() -> RevisedMissionProposal:
    return RevisedMissionProposal(
        remaining_waypoints=[MissionItem(sequence=1, command=MissionCommand.RETURN_TO_LAUNCH)],
        recommended_action=RecommendedAction.RETURN_TO_LAUNCH,
        reason="Battery critical, returning home immediately.",
        confidence=0.9,
    )


# ---------------------------------------------------------------------
# Approval path -- reuse of the existing rule validator + battery check
# ---------------------------------------------------------------------


def test_safe_proposal_is_approved_and_produces_a_mission(monkeypatch):
    manager = _manager_at()
    context = _context(manager, battery_remaining_percent=0.5)
    result = ReplanningSafetyValidator().validate(
        _safe_continue_proposal(), context, manager.snapshot(), home_latitude_deg=HOME_LAT, home_longitude_deg=HOME_LON
    )

    assert result.status == SafetyValidationStatus.APPROVED
    assert result.approved is True
    assert result.errors == []
    assert result.approved_mission is not None
    assert [i.command for i in result.approved_mission.mission_items] == [
        MissionCommand.WAYPOINT, MissionCommand.RETURN_TO_LAUNCH,
    ]
    assert result.fallback_action is None


